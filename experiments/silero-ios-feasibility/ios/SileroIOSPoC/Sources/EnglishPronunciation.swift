/// CMUdict curriculum subset + small deterministic, best-effort OOV grapheme-to-phoneme fallback.
/// No network, Python, model, or per-fragment resource parsing. IT overrides live in TechnicalLexicon.
enum EnglishPronunciation {
    static let phonemeMap: [String:String] = [
        "AA":"а", "AE":"э", "AH":"а", "AO":"о", "AW":"ау", "AY":"ай",
        "B":"б", "CH":"ч", "D":"д", "DH":"з", "EH":"е", "ER":"ер",
        "EY":"эй", "F":"ф", "G":"г", "HH":"х", "IH":"и", "IY":"и",
        "JH":"дж", "K":"к", "L":"л", "M":"м", "N":"н", "NG":"нг",
        "OW":"оу", "OY":"ой", "P":"п", "R":"р", "S":"с", "SH":"ш",
        "T":"т", "TH":"т", "UH":"у", "UW":"у", "V":"в", "W":"в",
        "Y":"й", "Z":"з", "ZH":"ж"
    ]
    static func cyrillic(_ pronunciation: String) -> String {
        let phones = pronunciation.split(separator: " ").map { String($0.filter { !$0.isNumber }) }
        var result = "", i = 0
        while i < phones.count {
            if phones[i] == "Y", i + 1 < phones.count, phones[i + 1] == "UW" {
                result += result.isEmpty ? "ю" : "ью"; i += 2
            } else {
                // All dictionary phones are validated by the regression harness.
                result += phonemeMap[phones[i]]!; i += 1
            }
        }
        return result
    }
    static func known(_ word: String) -> String? {
        dictionary[word].map(cyrillic)
    }

    /// English orthography is ambiguous: dictionary always wins. These bounded rules cover
    /// novel words and inflections, not arbitrary proper names or all English exceptions.
    static func fallbackPhones(_ word: String) -> [String] {
        if let exact = dictionary[word] { return exact.split(separator:" ").map(String.init) }
        if word.count > 5 {
            for (suffix, phones) in [("ing",["IH","NG"]),("ment",["M","AH","N","T"]),("ity",["IH","T","IY"]),("ous",["AH","S"]),("er",["ER"])] {
                if word.hasSuffix(suffix) {
                    let stem=String(word.dropLast(suffix.count))
                    let base=dictionary[stem] != nil ? stem : dictionary[stem+"e"] != nil ? stem+"e" : stem
                    return fallbackPhones(base)+phones
                }
            }
            if word.hasSuffix("ed") {
                let stem=String(word.dropLast(2))
                let base=dictionary[stem] != nil ? stem : dictionary[stem+"e"] != nil ? stem+"e" : stem
                let phones=fallbackPhones(base)
                let last=phones.last?.filter { !$0.isNumber } ?? ""
                return phones + (["T","D"].contains(last) ? ["IH","D"] : ["P","K","F","S","SH","CH","TH"].contains(last) ? ["T"] : ["D"])
            }
        }
        let chars=Array(word)
        let vowels=Set("aeiouy")
        let long: [Character:String] = ["a":"EY","e":"IY","i":"AY","o":"OW","u":"UW","y":"AY"]
        let singles: [Character:[String]] = [
            "a":["AE"],"b":["B"],"c":["K"],"d":["D"],"e":["EH"],"f":["F"],"g":["G"],
            "h":["HH"],"i":["IH"],"j":["JH"],"k":["K"],"l":["L"],"m":["M"],"n":["N"],
            "o":["AA"],"p":["P"],"q":["K"],"r":["R"],"s":["S"],"t":["T"],"u":["AH"],
            "v":["V"],"w":["W"],"x":["K","S"],"y":["IY"],"z":["Z"]
        ]
        let groups:[(String,[String])] = [
            ("tion",["SH","AH","N"]),("sion",["ZH","AH","N"]),("tch",["CH"]),("igh",["AY"]),
            ("dge",["JH"]),("ph",["F"]),("th",["TH"]),("sh",["SH"]),("ch",["CH"]),
            ("ck",["K"]),("qu",["K","W"]),("ai",["EY"]),("ay",["EY"]),("oa",["OW"]),
            ("ee",["IY"]),("ea",["IY"]),("ie",["IY"]),("ou",["AW"]),("ow",["OW"]),
            ("oo",["UW"]),("ng",["NG"])
        ]
        var result:[String]=[], i=0
        while i < chars.count {
            let tail=String(chars[i...])
            if let group=groups.first(where:{tail.hasPrefix($0.0)}) {
                result += group.1; i += group.0.count; continue
            }
            let c=chars[i]
            // CVCe: final e is silent and changes the preceding vowel.
            if i == chars.count-1, c == "e", chars.count>2 { i += 1; continue }
            if let phone=long[c], i+2==chars.count-1, chars.last=="e", !vowels.contains(chars[i+1]) {
                result.append(phone)
            } else if c=="c", i+1<chars.count, "eiy".contains(chars[i+1]) {
                result.append("S")
            } else if c=="g", i+1<chars.count, "eiy".contains(chars[i+1]) {
                result.append("JH")
            } else {
                result += singles[c] ?? []
            }
            // Doubled consonants are one sound.
            i += (i+1<chars.count && chars[i+1]==c && !vowels.contains(c)) ? 2 : 1
        }
        return result
    }
    static func fallback(_ word: String) -> String {
        cyrillic(fallbackPhones(word).joined(separator:" "))
    }

